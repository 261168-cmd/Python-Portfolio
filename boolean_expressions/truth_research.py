# bool("") will print False because it is an empty string
print(bool(""))

# bool("0") will print True because the string contains a character and is not empty
print(bool("0"))

# bool(0) will print False because the integer value is zero
print(bool(0))

# bool(0.0) will print False because the floating-point value is zero
print(bool(0.0))

# bool("False") will print True because it is a non-empty string containing text
print(bool("False"))

